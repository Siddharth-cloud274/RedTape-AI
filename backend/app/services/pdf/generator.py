STORAGE_DIR = os.path.abspath(
    os.path.join(os.path.dirname(__file__), "..", "..", "..", "storage", "drafts")
)
os.makedirs(STORAGE_DIR, exist_ok=True)


def compute_file_sha256(filepath: str) -> str:
    """Computes SHA-256 hash of a file."""
    h = hashlib.sha256()
    with open(filepath, "rb") as f:
        while chunk := f.read(8192):
            h.update(chunk)
    return h.hexdigest()


def overlay_draft_watermark(page: pymupdf.Page) -> None:
    """Overlays an unambiguous unsubmitted draft header watermark at the top of the page."""
    rect = pymupdf.Rect(30, 12, 582, 28)
    banner_text = "UNSUBMITTED DRAFT • GENERATED BY REDTAPE AI • NOT AN OFFICIAL CERTIFICATE"
    page.insert_textbox(
        rect,
        banner_text,
        fontsize=8.0,
        fontname="helv",
        color=(0.85, 0.15, 0.15),  # bold red draft disclaimer
        align=1,  # Center
    )


def generate_pdf_draft(
    conversation_id: str,
    template_id: str = "kolkata_domicile_higher_studies",
    custom_field_values: Optional[Dict[str, str]] = None,
    document_id: Optional[str] = None,
    version: int = 1,
) -> DocumentMetadataResponse:
    """
    Generates a draft PDF by overlaying applicant data onto the verified official template.
    Preserves template integrity, ensures unsubmitted draft banner, leaves signature boxes blank.
    """
    template = get_template(template_id)
    if not template:
        raise ValueError(f"Unknown official template: {template_id}")

    if not os.path.exists(template.file_path):
        raise FileNotFoundError(f"Template master file not found: {template.file_path}")

    # Verify template integrity
    current_hash = compute_file_sha256(template.file_path)
    if current_hash != template.sha256_hash:
        raise ValueError(f"Template integrity compromised: hash mismatch for {template_id}")

    # Check readiness and facts
    readiness = validate_document_readiness(
        conversation_id, template_id=template_id, custom_overrides=custom_field_values
    )
    facts = get_conversation_facts(conversation_id)

    doc_id = document_id or str(uuid.uuid4())
    filename = f"{doc_id}_v{version}.pdf"
    output_filepath = os.path.join(STORAGE_DIR, filename)

    # Open template with PyMuPDF
    doc = pymupdf.open(template.file_path)

    # Apply watermark to all pages
    for page in doc:
        overlay_draft_watermark(page)

    filled_fields: Dict[str, str] = {}
    missing_fields: List[str] = []

    # Overlay fields
    for field_name, config in KOLKATA_DOMICILE_FIELD_MAP.items():
        val = resolve_field_value(field_name, facts, custom_field_values)
        if val:
            page_idx = config["page"]
            if page_idx < len(doc):
                page = doc[page_idx]
                rect = pymupdf.Rect(*config["rect"])
                font_size = config.get("font_size", 10.0)
                align = config.get("align", 0)
                
                # Insert text into specified static coordinates
                page.insert_textbox(
                    rect,
                    str(val),
                    fontsize=font_size,
                    fontname="helv",
                    color=(0.1, 0.1, 0.2),  # Professional deep dark blue/charcoal
                    align=align,
                )
                filled_fields[field_name] = str(val)
        else:
            if field_name in REQUIRED_FIELDS:
                missing_fields.append(field_name)

    # Save generated draft
    doc.save(output_filepath, deflate=True)
    doc.close()

    # Self-verification: Ensure generated file opens without error and retains page count
    verify_doc = pymupdf.open(output_filepath)
    if verify_doc.page_count != template.page_count:
        verify_doc.close()
        raise RuntimeError("Generated PDF page count does not match template")
    verify_doc.close()

    now_iso = datetime.now(timezone.utc).isoformat()
    readiness_status = (
        DocumentReadinessStatus.DRAFT_GENERATED
        if not missing_fields
        else DocumentReadinessStatus.DRAFT_NEEDS_REVIEW
    )

    metadata_json = json.dumps({
        "filled_fields": filled_fields,
        "missing_fields": missing_fields,
        "sha256": compute_file_sha256(output_filepath),
    })

    # Record in database
    with get_db() as conn:
        cursor = conn.cursor()
        cursor.execute(
            """
            INSERT INTO generated_documents (
                id, conversation_id, template_id, version, status,
                file_path, missing_fields, metadata_json, created_at, updated_at
            )
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            ON CONFLICT(id) DO UPDATE SET
                version = excluded.version,
                status = excluded.status,
                file_path = excluded.file_path,
                missing_fields = excluded.missing_fields,
                metadata_json = excluded.metadata_json,
                updated_at = excluded.updated_at
            """,
            (
                doc_id,
                conversation_id,
                template_id,
                version,
                readiness_status.value,
                output_filepath,
                json.dumps(missing_fields),
                metadata_json,
                now_iso,
                now_iso,
            ),
        )

    return DocumentMetadataResponse(
        document_id=doc_id,
        conversation_id=conversation_id,
        template_id=template_id,
        title=template.title,
        issuing_authority=template.issuing_authority,
        jurisdiction=template.jurisdiction,
        version=version,
        status=readiness_status.value,
        readiness_status=readiness_status,
        missing_fields=missing_fields,
        filled_fields=filled_fields,
        preview_url=f"/api/documents/{doc_id}/preview",
        download_url=f"/api/documents/{doc_id}/download",
        source_portal_url=template.source_portal_url,
        created_at=now_iso,
        updated_at=now_iso,
    )


def get_draft_metadata(document_id: str) -> Optional[DocumentMetadataResponse]:
    """Retrieves document draft metadata from database."""
    with get_db() as conn:
        cursor = conn.cursor()
        cursor.execute(
            """
            SELECT id, conversation_id, template_id, version, status,
                   file_path, missing_fields, metadata_json, created_at, updated_at
            FROM generated_documents
            WHERE id = ?
            """,
            (document_id,),
        )
        row = cursor.fetchone()
        if not row:
            return None

        template = get_template(row["template_id"])
        meta = json.loads(row["metadata_json"]) if row["metadata_json"] else {}
        missing = json.loads(row["missing_fields"]) if row["missing_fields"] else []

        return DocumentMetadataResponse(
            document_id=row["id"],
            conversation_id=row["conversation_id"],
            template_id=row["template_id"],
            title=template.title if template else "Official Document",
            issuing_authority=template.issuing_authority if template else "State Authority",
            jurisdiction=template.jurisdiction if template else "General",
            version=row["version"],
            status=row["status"],
            readiness_status=DocumentReadinessStatus(row["status"]),
            missing_fields=missing,
            filled_fields=meta.get("filled_fields", {}),
            preview_url=f"/api/documents/{row['id']}/preview",
            download_url=f"/api/documents/{row['id']}/download",
            source_portal_url=template.source_portal_url if template else "",
            created_at=row["created_at"],
            updated_at=row["updated_at"],
        )


def get_latest_document_for_conversation(conversation_id: str, db: sqlite3.Connection = None) -> Optional[DocumentMetadataResponse]:
    """Retrieves the most recent document draft for a conversation."""
    def _fetch(conn: sqlite3.Connection):
        cursor = conn.cursor()
        cursor.execute(
            """
            SELECT id FROM generated_documents
            WHERE conversation_id = ?
            ORDER BY version DESC, updated_at DESC
            LIMIT 1
            """,
            (conversation_id,),
        )
        row = cursor.fetchone()
        return row["id"] if row else None

    doc_id = _fetch(db) if db is not None else None
    if not doc_id and db is None:
        with get_db() as conn:
            doc_id = _fetch(conn)

    return get_draft_metadata(doc_id) if doc_id else None


def get_draft_file_path(document_id: str) -> Optional[str]:
    """Retrieves safe file path for a generated draft."""
    with get_db() as conn:
        cursor = conn.cursor()
        cursor.execute("SELECT file_path FROM generated_documents WHERE id = ?", (document_id,))
        row = cursor.fetchone()
        if row and row["file_path"] and os.path.exists(row["file_path"]):
            # Prevent path traversal outside STORAGE_DIR
            resolved = os.path.abspath(row["file_path"])
            if resolved.startswith(os.path.abspath(STORAGE_DIR)):
                return resolved
    return None


def regenerate_pdf_draft(
    document_id: str, updated_fields: Optional[Dict[str, str]] = None
) -> DocumentMetadataResponse:
    """Regenerates a new version of the document with updated field values."""
    existing = get_draft_metadata(document_id)
    if not existing:
        raise ValueError(f"Draft not found: {document_id}")

    new_version = existing.version + 1
    # Merge existing filled fields with updated fields
    merged_fields = {**existing.filled_fields, **(updated_fields or {})}

    return generate_pdf_draft(
        conversation_id=existing.conversation_id,
        template_id=existing.template_id,
        custom_field_values=merged_fields,
        document_id=document_id,
        version=new_version,
    )
